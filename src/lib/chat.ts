import type { Account, Chat, ChatStatus, Message } from "../types";

export function lastMessage(chat: Chat): Message | undefined {
  return chat.last;
}

export function unreadCount(chat: Chat): number {
  return chat.unread;
}

/**
 * Manual status wins; automated mail nobody answers is Done; otherwise whoever wrote last
 * decides who owes a reply.
 */
export function effectiveStatus(chat: Chat): ChatStatus {
  if (chat.manualStatus) return chat.manualStatus;
  if (chat.automated) return "done";
  return lastMessage(chat)?.outgoing ? "waiting" : "needs_reply";
}

export function chatTitle(chat: Chat): string {
  return chat.participants.map((p) => p.name.split(" ")[0]).join(", ");
}

export function chatDisplayName(chat: Chat): string {
  return chat.participants.length === 1 ? chat.participants[0].name : chatTitle(chat);
}

export function accountAddresses(account: Account): string[] {
  return [account.email, ...account.aliases];
}

/**
 * The address a reply goes out from: the one the conversation is using, read back from the
 * message being answered, or else the account's default.
 */
export function replyFrom(account: Account, messages: Message[], target?: Message): string {
  const addresses = accountAddresses(account);
  const start = target ? messages.findIndex((m) => m.id === target.id) : messages.length - 1;
  for (let i = start; i >= 0; i--) {
    const m = messages[i];
    const used = m.outgoing ? m.from.address : m.ownAddress;
    if (used && addresses.includes(used)) return used;
  }
  return account.defaultFrom;
}

const REPLY_PREFIX = /^\s*((re|fwd?|aw|wg|odp|sv|vs|ha|відп|пересл)\s*(\[\d+\])?\s*:\s*)+/i;

/** Strips Re:/Fwd: style prefixes in the languages these mailboxes actually see. */
export function normalizeSubject(subject: string): string {
  return subject.replace(REPLY_PREFIX, "").trim();
}

export function initials(name: string): string {
  const parts = name
    .replace(/^(doc\.|prof\.|mgr\.|ing\.|phdr\.|dr\.)\s*/gi, "")
    .split(/\s+/)
    .filter(Boolean);
  return ((parts[0]?.[0] ?? "") + (parts[1]?.[0] ?? "")).toUpperCase();
}

export function matchesQuery(chat: Chat, query: string): boolean {
  const q = query.trim().toLocaleLowerCase();
  if (!q) return true;
  return (
    chat.participants.some(
      (p) => p.name.toLocaleLowerCase().includes(q) || p.address.toLocaleLowerCase().includes(q),
    ) ||
    // Newest message only: the instant local check. All mail is searched with FTS5 in the
    // core (lib/search.ts), whose results replace this once they arrive.
    chat.last.subject.toLocaleLowerCase().includes(q) ||
    chat.last.body.toLocaleLowerCase().includes(q)
  );
}

/** Mirrors `parse::AUTOMATED_SENDER` in the Rust core. */
const NO_REPLY_LOCAL =
  /^(no[-_.]?reply|do[-_.]?not[-_.]?reply|mailer[-_.]?daemon|postmaster|bounces?|notifications?|newsletters?)([-_.+].*)?$/i;

/** A chat with no-reply addresses only (noreply@, notifications@, …): writing there reaches nobody. */
export function isNoReplyChat(chat: Chat): boolean {
  return (
    chat.participants.length > 0 &&
    chat.participants.every((p) => NO_REPLY_LOCAL.test(p.address.split("@")[0]))
  );
}

/** `unsub-…@`, `x+unsubscribe_…@`, `leave-…@` (list servers), `…@unsubscribe2.example.com`. */
const UNSUB_LOCAL = /(^|[._+-])unsub|^leave-/i;
const UNSUB_DOMAIN = /(^|\.)unsub/i;
const UNSUB_SUBJECT = /^\s*(unsubscribe|unsub[-_ ]\S*|odhlásiť|odhlásit|відписатися)\s*$/i;
const UNSUB_BODY =
  /automatically generated by (gmail|apple mail|outlook)|sent this email to unsubscribe|unsubscribe request|requested to unsubscribe/i;

function isUnsubscribeAddress(address: string): boolean {
  const at = address.lastIndexOf("@");
  if (at < 0) return UNSUB_LOCAL.test(address);
  return UNSUB_LOCAL.test(address.slice(0, at)) || UNSUB_DOMAIN.test(address.slice(at + 1));
}

/**
 * Chats that only exist because a mail client sent a one-click unsubscribe ("This message
 * was automatically generated by Gmail.", "Apple Mail sent this email to unsubscribe from
 * the message …"): with an unsubscribe address, or our own message that is just an
 * unsubscribe request.
 */
export function isUnsubscribeChat(chat: Chat): boolean {
  if (chat.participants.every((p) => isUnsubscribeAddress(p.address))) return true;
  const last = chat.last;
  return last.outgoing && (UNSUB_SUBJECT.test(last.subject) || UNSUB_BODY.test(last.body));
}
